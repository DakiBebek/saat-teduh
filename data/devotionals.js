// Generator Otomatis Renungan Harian 365 Hari yang Konsisten Berdasarkan Tanggal
function getDevotionalForDate(targetDate = new Date()) {
  const start = new Date(targetDate.getFullYear(), 0, 0);
  const diff = targetDate - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // Jika dalam indeks koleksi inti:
  const baseIndex = (dayOfYear - 1) % DEVOTIONAL_ARCHIVE.length;
  const baseDevotional = DEVOTIONAL_ARCHIVE[Math.abs(baseIndex)];
  
  // Format tanggal dalam bahasa Indonesia
  const dateStr = targetDate.toLocaleDateString('id-ID', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });

  const isoDate = targetDate.toISOString().split('T')[0];

  // Gunakan variasi tema bila siklus berulang
  const themeVariation = THEMES_LIBRARY[(dayOfYear + targetDate.getFullYear()) % THEMES_LIBRARY.length];

  return {
    ...baseDevotional,
    dateString: dateStr,
    isoDate: isoDate,
    dayOfYear: dayOfYear,
    dailyQuote: `Renungan Saat Teduh • Hari ke-${dayOfYear} dari 365 Hari Berjalan Bersama Tuhan`,
    image: baseDevotional.image || themeVariation.image,
    imageCaption: baseDevotional.imageCaption || themeVariation.imageCaption
  };
}
